def search_architectures(args):
    data_bundle = prepare_training_data(args)

    search_space = list(product(
        args.search_hidden_dims,
        args.search_num_layers,
        args.search_dropouts,
    ))
    if not search_space:
        raise ValueError("Search space is empty")

    trials_root = os.path.join(args.save_dir, "search_trials")
    os.makedirs(trials_root, exist_ok=True)

    results = []
    total_trials = len(search_space)
    print(f"Running architecture search over {total_trials} candidate(s)")
    for trial_idx, (hidden_dim, num_layers, dropout) in enumerate(search_space, start=1):
        trial_name = (
            f"trial_{trial_idx:02d}_h{hidden_dim}_l{num_layers}_d"
            f"{str(dropout).replace('.', 'p')}"
        )
        trial_dir = os.path.join(trials_root, trial_name)
        print(
            f"\n=== Trial {trial_idx}/{total_trials} | "
            f"hidden_dim={hidden_dim}, num_layers={num_layers}, dropout={dropout} ==="
        )
        trial_result = run_training_job(
            args,
            data_bundle,
            save_dir=trial_dir,
            hidden_dim=hidden_dim,
            num_layers=num_layers,
            dropout=dropout,
            epochs=args.search_epochs,
            patience=args.search_patience,
            resume_from=None,
            export_best_onnx=False,
            create_plots=False,
            save_epoch_checkpoints=False,
            seed=42 + trial_idx,
            run_label=trial_name,
        )
        trial_result["trial_name"] = trial_name
        results.append(trial_result)

    results_df = pd.DataFrame(results).sort_values(
        by=["best_val_auc", "best_val_loss"],
        ascending=[False, True],
    )
    results_path = os.path.join(args.save_dir, "architecture_search_results.csv")
    results_df.to_csv(results_path, index=False)
    print(f"Saved search summary -> {results_path}")

    best_row = results_df.iloc[0]
    best_config = {
        "hidden_dim": int(best_row["hidden_dim"]),
        "num_layers": int(best_row["num_layers"]),
        "dropout": float(best_row["dropout"]),
        "search_epochs": int(args.search_epochs),
        "search_patience": int(args.search_patience),
        "best_val_auc": float(best_row["best_val_auc"]),
        "best_val_loss": float(best_row["best_val_loss"]),
        "trial_name": best_row["trial_name"],
    }
    best_config_path = os.path.join(args.save_dir, "best_search_config.json")
    with open(best_config_path, "w", encoding="ascii") as handle:
        json.dump(best_config, handle, indent=2)
    print(f"Best search config  -> {best_config_path}")

    print(
        "\nRetraining best architecture with full schedule: "
        f"hidden_dim={best_config['hidden_dim']}, "
        f"num_layers={best_config['num_layers']}, "
        f"dropout={best_config['dropout']}"
    )
    final_result = run_training_job(
        args,
        data_bundle,
        save_dir=args.save_dir,
        hidden_dim=best_config["hidden_dim"],
        num_layers=best_config["num_layers"],
        dropout=best_config["dropout"],
        epochs=args.epochs,
        patience=args.patience,
        resume_from=None,
        export_best_onnx=True,
        create_plots=True,
        save_epoch_checkpoints=True,
        seed=42,
        run_label="best_search_model",
    )

    final_summary = {
        "search": best_config,
        "final_train": final_result,
    }
    final_summary_path = os.path.join(args.save_dir, "architecture_search_summary.json")
    with open(final_summary_path, "w", encoding="ascii") as handle:
        json.dump(final_summary, handle, indent=2)
    print(f"Saved final summary -> {final_summary_path}")
    return final_result


def run_diagnostics(args):
    set_seed(42)

    if not os.path.exists(args.geo):
        print(f"ERROR: geometry file not found: {args.geo}", file=sys.stderr)
        sys.exit(1)

    geo = pd.read_csv(args.geo)
    geo_dict = icecube_geom(geo)

    dataset = TauDataloader(
        nue_dbs=args.nue_dbs,
        tau_dbs=args.tau_dbs,
        geo_dict=geo_dict,
        max_events_per_class=args.max_events,
        charge_threshold=args.charge_threshold,
    )

    tau_indices = [i for i in range(len(dataset)) if dataset[i].y.item() == 1]
    nue_indices = [i for i in range(len(dataset)) if dataset[i].y.item() == 0]

    n_each = min(args.n_samples // 2, len(tau_indices), len(nue_indices))
    print(f"Sampling {n_each} tau + {n_each} nue events for feature diagnostics...")

    n_energy_each = min(args.n_energy_events // 2, len(tau_indices), len(nue_indices))
    print(f"Sampling {n_energy_each} tau + {n_energy_each} nue events for energy histogram...")

    def summarise(indices, n_take):
        feats = []
        for i in tqdm(indices[:n_take], desc="Summarise", leave=False):
            g = dataset[i]
            x = g.x.numpy()
            if x.shape[0] < 2:
                continue
            feats.append(np.concatenate([
                x.mean(axis=0),
                x.std(axis=0),
                x.max(axis=0),
            ]))
        return np.array(feats)

    # log_energy is feature index 12 and equals log10(E)/6
    def collect_energy(indices, n_take):
        energies = []
        for i in tqdm(indices[:n_take], desc="Collect energy", leave=False):
            g = dataset[i]
            x = g.x.numpy()
            if x.shape[0] < 1:
                continue
            log_e_norm = float(x[0, 12])
            energy = 10.0 ** (6.0 * log_e_norm)
            energies.append(energy)
        return np.array(energies, dtype=np.float64)

    tau_feats = summarise(tau_indices, n_each)
    nue_feats = summarise(nue_indices, n_each)

    if tau_feats.ndim < 2 or nue_feats.ndim < 2:
        print("ERROR: Not enough valid events for diagnostics.", file=sys.stderr)
        sys.exit(1)

    stat_names = (
        [f"mean_{f}" for f in FEATURE_NAMES] +
        [f"std_{f}" for f in FEATURE_NAMES] +
        [f"max_{f}" for f in FEATURE_NAMES]
    )

    sep_scores = []
    for i, name in enumerate(stat_names):
        t_mean = tau_feats[:, i].mean()
        n_mean = nue_feats[:, i].mean()
        t_std = tau_feats[:, i].std() + 1e-6
        n_std = nue_feats[:, i].std() + 1e-6
        sep = abs(t_mean - n_mean) / (0.5 * (t_std + n_std))
        sep_scores.append((sep, name, t_mean, n_mean))

    sep_scores.sort(reverse=True)

    print(f"\n{'Feature':<25} {'tau mean':>12} {'nue mean':>12} {'sep score':>12}")
    print("-" * 65)
    for sep, name, t_mean, n_mean in sep_scores[:15]:
        print(f"{name:<25} {t_mean:>12.4f} {n_mean:>12.4f} {sep:>12.4f}")

    # Feature separation figure
    fig, axes = plt.subplots(2, 4, figsize=(16, 8), facecolor="black")
    axes = axes.flatten()
    for idx, (sep, name, _, _) in enumerate(sep_scores[:8]):
        feat_idx = stat_names.index(name)
        ax = axes[idx]
        ax.hist(
            tau_feats[:, feat_idx], bins=40, alpha=0.6,
            color="cyan", label="nutau", density=True
        )
        ax.hist(
            nue_feats[:, feat_idx], bins=40, alpha=0.6,
            color="orange", label="nue", density=True
        )
        ax.set_title(f"{name}\nsep={sep:.3f}", color="white", fontsize=8)
        ax.set_facecolor("black")
        ax.tick_params(colors="white", labelsize=7)
        for spine in ["bottom", "left"]:
            ax.spines[spine].set_color("gray")
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        legend = ax.legend(fontsize=7)
        for text in legend.get_texts():
            text.set_color("white")
        legend.get_frame().set_facecolor("black")
        legend.get_frame().set_edgecolor("gray")

    fig.suptitle("Top 8 separating features: nutau vs nue", color="white", fontsize=12)
    plt.tight_layout()

    os.makedirs(args.save_dir, exist_ok=True)
    out_path = os.path.join(args.save_dir, "feature_separation.png")
    plt.savefig(out_path, dpi=150, bbox_inches="tight", facecolor="black")
    plt.close()
    print(f"\nSaved -> {out_path}")

    # Energy histogram figure
    tau_e = collect_energy(tau_indices, n_energy_each)
    nue_e = collect_energy(nue_indices, n_energy_each)

    if len(tau_e) > 0 and len(nue_e) > 0:
        tau_loge = np.log10(np.clip(tau_e, 1.0, None))
        nue_loge = np.log10(np.clip(nue_e, 1.0, None))
        lo = min(tau_loge.min(), nue_loge.min())
        hi = max(tau_loge.max(), nue_loge.max())
        bins = np.linspace(lo, hi, 40)

        fig2, ax2 = plt.subplots(figsize=(8, 5), facecolor="black")
        fig2.patch.set_facecolor("black")
        ax2.set_facecolor("black")

        ax2.hist(tau_loge, bins=bins, alpha=0.6, density=True, color="cyan", label="nutau")
        ax2.hist(nue_loge, bins=bins, alpha=0.6, density=True, color="orange", label="nue")

        ax2.tick_params(colors="white")
        for spine in ["bottom", "left"]:
            ax2.spines[spine].set_color("gray")
        ax2.spines["top"].set_visible(False)
        ax2.spines["right"].set_visible(False)

        ax2.set_title("Energy distribution", color="white")
        ax2.set_xlabel("log10(Energy [GeV])", color="white")
        ax2.set_ylabel("Density", color="white")

        legend = ax2.legend(fontsize=9)
        for text in legend.get_texts():
            text.set_color("white")
        legend.get_frame().set_facecolor("black")
        legend.get_frame().set_edgecolor("gray")

        energy_out = os.path.join(args.save_dir, "energy_histogram.png")
        plt.tight_layout()
        plt.savefig(energy_out, dpi=150, bbox_inches="tight", facecolor="black")
        plt.close()
        print(f"Saved -> {energy_out}")
    else:
        print("Skipped energy histogram: not enough valid events.")

def plot_node_features(args):
    """
    Plot 1: Grid of per-node feature histograms (tau vs nue) for all 13 features.
    Plot 2: Pearson correlation heatmap of node features, one panel per class.
    """
    set_seed(42)

    geo      = pd.read_csv(args.geo)
    geo_dict = icecube_geom(geo)

    dataset = TauDataloader(
        nue_dbs              = args.nue_dbs,
        tau_dbs              = args.tau_dbs,
        geo_dict             = geo_dict,
        max_events_per_class = args.max_events,
        charge_threshold     = args.charge_threshold,
    )

    tau_nodes, nue_nodes = [], []
    for i in tqdm(range(len(dataset)), desc="Collecting node features"):
        g = dataset[i]
        x = g.x.numpy()           # shape (n_nodes, 13)
        if g.y.item() == 1:
            tau_nodes.append(x)
        else:
            nue_nodes.append(x)

    tau_arr = np.concatenate(tau_nodes, axis=0)   # (N_tau_nodes, 13)
    nue_arr = np.concatenate(nue_nodes, axis=0)   # (N_nue_nodes, 13)
    print(f"tau nodes: {tau_arr.shape[0]:,}   nue nodes: {nue_arr.shape[0]:,}")

    os.makedirs(args.save_dir, exist_ok=True)

    # ----------------------------------------------------------------
    # Plot 1 -- per-feature histograms  (4 cols × 4 rows, last row
    #           has 1 feature + AUC summary)
    # ----------------------------------------------------------------
    ncols = 4
    nrows = (N_FEATURES + ncols - 1) // ncols   # ceil division
    fig, axes = plt.subplots(nrows, ncols,
                              figsize=(5 * ncols, 4 * nrows),
                              facecolor="black")
    fig.patch.set_facecolor("black")
    axes_flat = axes.flatten()

    def _style(ax, title):
        ax.set_facecolor("black")
        ax.tick_params(colors="white", labelsize=8)
        for s in ["bottom", "left"]:
            ax.spines[s].set_color("gray")
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.set_title(title, color="white", fontsize=9)
        ax.set_ylabel("density", color="white", fontsize=8)

    for fi, name in enumerate(FEATURE_NAMES):
        ax = axes_flat[fi]
        t  = tau_arr[:, fi]
        n  = nue_arr[:, fi]

        # Clip to [1st, 99th] percentile to avoid extreme outlier bins
        lo = np.percentile(np.concatenate([t, n]), 1)
        hi = np.percentile(np.concatenate([t, n]), 99)
        bins = np.linspace(lo, hi, 50)

        ax.hist(t, bins=bins, density=True, alpha=0.65, color="cyan",   label="nutau")
        ax.hist(n, bins=bins, density=True, alpha=0.65, color="orange", label="nue")

        # Separation score (Fisher-style)
        sep = abs(t.mean() - n.mean()) / (0.5 * (t.std() + n.std()) + 1e-9)
        _style(ax, f"{name}  [sep={sep:.2f}]")

        legend = ax.legend(fontsize=7)
        for txt in legend.get_texts():
            txt.set_color("white")
        legend.get_frame().set_facecolor("black")
        legend.get_frame().set_edgecolor("gray")

    # Hide any unused subplots
    for fi in range(N_FEATURES, len(axes_flat)):
        axes_flat[fi].set_visible(False)

    fig.suptitle(
        "Per-node feature distributions: nutau (cyan) vs nue (orange)",
        color="white", fontsize=12, y=1.01,
    )
    plt.tight_layout()
    p1 = os.path.join(args.save_dir, "node_feature_histograms.png")
    plt.savefig(p1, dpi=150, bbox_inches="tight", facecolor="black")
    plt.close()
    print(f"Saved -> {p1}")

    # ----------------------------------------------------------------
    # Plot 2 -- correlation heatmaps (tau | nue side by side)
    # ----------------------------------------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(18, 7), facecolor="black")
    fig.patch.set_facecolor("black")

    for ax, arr, label, cmap in zip(
        axes,
        [tau_arr, nue_arr],
        ["nutau", "nue"],
        ["PuBu", "OrRd"],
    ):
        corr = np.corrcoef(arr.T)   # (13, 13)

        im = ax.imshow(corr, vmin=-1, vmax=1, cmap=cmap, aspect="auto")
        plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

        ax.set_xticks(range(N_FEATURES))
        ax.set_yticks(range(N_FEATURES))
        ax.set_xticklabels(FEATURE_NAMES, rotation=45, ha="right",
                           fontsize=7, color="white")
        ax.set_yticklabels(FEATURE_NAMES, fontsize=7, color="white")
        ax.set_facecolor("black")
        ax.tick_params(colors="white")
        ax.set_title(f"Feature correlations — {label}", color="white", fontsize=11)

        # Annotate cells with correlation value
        for i in range(N_FEATURES):
            for j in range(N_FEATURES):
                ax.text(j, i, f"{corr[i, j]:.2f}",
                        ha="center", va="center",
                        fontsize=5, color="white" if abs(corr[i, j]) < 0.7 else "black")

    plt.tight_layout()
    p2 = os.path.join(args.save_dir, "node_feature_correlations.png")
    plt.savefig(p2, dpi=150, bbox_inches="tight", facecolor="black")
    plt.close()
    print(f"Saved -> {p2}")

