def event_stream(db_file):
    """
    Stream events row by row from SQLite, joining truth info.
    Only events with energy > 5e4 are selected.
    Yields (event_no, pulse_rows, meta_dict) per event.
    meta_dict keys: energy
    """
    if not os.path.exists(db_file):
        raise FileNotFoundError(f"DB file not found: {db_file}")

    conn = sqlite3.connect(db_file)
    cols = [r[1] for r in conn.execute("PRAGMA table_info(truth)").fetchall()]

    if "energy" not in cols:
        raise RuntimeError(f"'energy' column missing from truth table in {db_file}")

    query = """
        SELECT p.event_no, p.dom_x, p.dom_y, p.dom_z, p.dom_time, p.charge,
            t.energy
        FROM   CleanedROIPulses p
        JOIN   truth            t ON p.event_no = t.event_no
        ORDER  BY p.event_no
    """

    cursor        = conn.cursor()
    cursor.execute(query)
    current_event = None
    buffer        = []
    meta_store    = {}

    for row in cursor:
        event_no = row[0]
        pulse    = row[:6]
        energy   = row[6]

        if current_event is None:
            current_event = event_no

        if event_no != current_event:
            yield current_event, buffer, meta_store.get(current_event, {})
            buffer        = []
            current_event = event_no

        buffer.append(pulse)

        if event_no not in meta_store:
            meta_store[event_no] = {"energy": float(energy)}

    if buffer:
        yield current_event, buffer, meta_store.get(current_event, {})

    conn.close()

def icecube_geom(geo_df):
    """Maps (rounded dom_x, dom_y, dom_z) -> string number."""
    geo_dict = {}
    for _, row in geo_df.iterrows():
        key = (round(float(row.dom_x), 1),
               round(float(row.dom_y), 1),
               round(float(row.dom_z), 1))
        geo_dict[key] = int(row.string)
    return geo_dict

def event_to_string_graph(rows, geo_dict, meta=None,
                           k=16, t_scale=500.0, xyz_scale=500.0,
                           charge_threshold=0.0):
    """
    Convert raw pulse rows for one event into a PyG Data object.
    Each node represents one detector string (not one DOM hit).

    Node features (13):
        0  str_x          string XY position x
        1  str_y          string XY position y
        2  z_centroid     charge-weighted Z centroid
        3  z_asym         (Q_top - Q_bot) / Q_total       <- tau signature
        4  t_mean         charge-weighted mean time
        5  t_asym         (Q_early - Q_late) / Q_total    <- tau signature
        6  q_log          log total charge on string
        7  n_doms         number of hit DOMs (normalised)
        8  t_spread       std of hit times
        9  z_rel          z_centroid relative to event centroid  <- tau
        10 t_first        time of first hit on string
        11 q_frac         string charge fraction of event
        12 log_energy     log10(energy) / 6  (from truth)
    """
    rows   = np.array(rows, dtype=object)
    x_hits = rows[:, 1].astype(float)
    y_hits = rows[:, 2].astype(float)
    z_hits = rows[:, 3].astype(float)
    t_hits = rows[:, 4].astype(float)
    q_hits = rows[:, 5].astype(float)

    # Time window: keep [t0, t0 + 1500 ns]
    t0   = t_hits.min()
    mask = (t_hits >= t0) & (t_hits <= t0 + 1500.0)
    x_hits, y_hits, z_hits = x_hits[mask], y_hits[mask], z_hits[mask]
    t_hits, q_hits          = t_hits[mask], q_hits[mask]
    t_hits                  = t_hits - t0

    # Charge threshold: keep only DOM hits with charge above threshold
    q_mask = q_hits > charge_threshold
    x_hits, y_hits, z_hits = x_hits[q_mask], y_hits[q_mask], z_hits[q_mask]
    t_hits, q_hits          = t_hits[q_mask], q_hits[q_mask]

    def _fallback():
        return Data(
            x          = torch.zeros((1, N_FEATURES), dtype=torch.float),
            edge_index = torch.zeros((2, 0),          dtype=torch.long),
        )

    if len(t_hits) < 2:
        return _fallback()

    # Map each hit to a string via geometry lookup
    string_ids = np.array([
        geo_dict.get((round(xi, 1), round(yi, 1), round(zi, 1)), -1)
        for xi, yi, zi in zip(x_hits, y_hits, z_hits)
    ])
    valid = string_ids >= 0
    x_hits, y_hits, z_hits     = x_hits[valid], y_hits[valid], z_hits[valid]
    t_hits, q_hits, string_ids = t_hits[valid], q_hits[valid], string_ids[valid]

    if len(t_hits) < 2:
        return _fallback()

    q_total    = q_hits.sum() + 1e-6
    z_q_center = np.sum(q_hits * z_hits) / q_total
    log_energy = np.log10(max(float(meta.get("energy", 1.0)), 1.0)) / 6.0 \
                 if meta else 0.0

    node_feats     = []
    unique_strings = np.unique(string_ids)

    for s in unique_strings:
        mask_s  = string_ids == s
        q_s     = q_hits[mask_s]
        t_s     = t_hits[mask_s]
        z_s     = z_hits[mask_s]
        x_s     = x_hits[mask_s]
        y_s     = y_hits[mask_s]
        q_sum_s = q_s.sum() + 1e-6

        str_x      = x_s[0] / xyz_scale
        str_y      = y_s[0] / xyz_scale
        z_centroid = np.sum(q_s * z_s) / q_sum_s
        z_mid      = np.median(z_s)
        q_top      = q_s[z_s >= z_mid].sum()
        q_bot      = q_s[z_s <  z_mid].sum()
        z_asym     = (q_top - q_bot) / q_sum_s
        t_mean_s   = np.sum(q_s * t_s) / q_sum_s
        q_early    = q_s[t_s <= 750.0].sum()
        q_late     = q_s[t_s >  750.0].sum()
        t_asym     = (q_early - q_late) / q_sum_s
        q_log      = np.log1p(q_sum_s)
        n_doms     = len(np.unique(z_s)) / 60.0
        t_spread   = float(t_s.std()) / t_scale if len(t_s) > 1 else 0.0
        z_rel      = (z_centroid - z_q_center) / xyz_scale
        t_first    = float(t_s.min()) / t_scale
        q_frac     = q_sum_s / q_total
        
        node_feats.append([
            str_x,                  # 0
            str_y,                  # 1
            z_centroid / xyz_scale, # 2
            z_asym,                 # 3  <- tau signature
            t_mean_s / t_scale,     # 4
            t_asym,                 # 5  <- tau signature
            q_log,                  # 6
            n_doms,                 # 7
            t_spread,               # 8
            z_rel,                  # 9  <- tau signature
            t_first,                # 10
            q_frac,                 # 11
            log_energy,             # 12
        ])

    node_feats = np.array(node_feats, dtype=np.float32)
    x_tensor   = torch.tensor(node_feats, dtype=torch.float)
    # pos        = x_tensor[:, :2]
    # edge_index = knn_graph(pos, k=min(k, len(x_tensor) - 1), loop=False)
    # edge_index = knn_graph(pos, k=16, loop=False)
    pos        = x_tensor[:, [0, 1, 2]]
    # Current — no guard, crashes on small events
    edge_index = knn_graph(pos, k=16, loop=False)

    # Fix
    k_actual   = min(16, x_tensor.size(0) - 1)
    if k_actual < 1:
        return _fallback()
    edge_index = knn_graph(pos, k=k_actual, loop=False)
    
    return Data(x=x_tensor, edge_index=edge_index)

class TauDataloader(InMemoryDataset):
    def __init__(self, nue_dbs, tau_dbs, geo_dict,
                 max_events_per_class=None, charge_threshold=0.0):
        super().__init__()

        if isinstance(nue_dbs, str): nue_dbs = [nue_dbs]
        if isinstance(tau_dbs, str): tau_dbs = [tau_dbs]

        for path in nue_dbs + tau_dbs:
            if not os.path.exists(path):
                raise FileNotFoundError(f"DB file not found: {path}")

        data_list = []

        # --- nutau ---
        print(f"Loading tau events from {len(tau_dbs)} file(s)...")
        count = 0
        for db in tqdm(tau_dbs, desc="  tau files", unit="file"):
            for eid, rows, meta in tqdm(
                event_stream(db),
                desc=f"    {os.path.basename(db)}",
                unit="ev", leave=False
            ):
                if max_events_per_class and count >= max_events_per_class:
                    break
                g   = event_to_string_graph(
                    rows, geo_dict, meta=meta, charge_threshold=charge_threshold
                )
                g.y = torch.tensor([1.0])
                data_list.append(g)
                count += 1
            if max_events_per_class and count >= max_events_per_class:
                break
        print(f"  -> Loaded {count} tau events")

        # --- nue ---
        print(f"Loading nue events from {len(nue_dbs)} file(s)...")
        count = 0
        for db in tqdm(nue_dbs, desc="  nue files", unit="file"):
            for eid, rows, meta in tqdm(
                event_stream(db),
                desc=f"    {os.path.basename(db)}",
                unit="ev", leave=False
            ):
                if max_events_per_class and count >= max_events_per_class:
                    break
                g   = event_to_string_graph(
                    rows, geo_dict, meta=meta, charge_threshold=charge_threshold
                )
                g.y = torch.tensor([0.0])
                data_list.append(g)
                count += 1
            if max_events_per_class and count >= max_events_per_class:
                break
        print(f"  -> Loaded {count} nue events")

        if len(data_list) == 0:
            raise RuntimeError("Dataset is empty -- check DB paths and table names.")

        print("Collating dataset...")
        self.data, self.slices = self.collate(data_list)
        print(f"  -> Total: {len(data_list)} events")

def collate_hit_sequences(batch):
    lengths = [sample["x"].size(0) for sample in batch]
    max_len = max(lengths)
    feat_dim = batch[0]["x"].size(1)

    x = torch.zeros((len(batch), max_len, feat_dim), dtype=torch.float32)
    mask = torch.ones((len(batch), max_len), dtype=torch.bool)
    y = torch.zeros(len(batch), dtype=torch.float32)

    for i, sample in enumerate(batch):
        seq = sample["x"]
        length = seq.size(0)
        x[i, :length] = seq
        mask[i, :length] = False
        y[i] = sample["y"]

    return {"x": x, "padding_mask": mask, "y": y}

class SuperGNN(nn.Module):

    def __init__(self, hidden_dim=256, input_dim=N_FEATURES, dropout=0.4, num_layers=7):
        super().__init__()

        self.node_mlp = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.BatchNorm1d(hidden_dim),
        )

        self.num_layers = num_layers
        self.convs = nn.ModuleList()
        self.bns = nn.ModuleList()
        for i in range(num_layers):
            in_dim = hidden_dim if i == 0 else hidden_dim * 4
            self.convs.append(TransformerConv(in_dim, hidden_dim, heads=4))
            self.bns.append(nn.BatchNorm1d(hidden_dim * 4))
        self.act = nn.ReLU()
        self.drop = nn.Dropout(dropout)

        # +1 for appended mean_q
        self.classifier = nn.Sequential(
            nn.Linear(hidden_dim * 4 + 1, 64),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(64, 1),
        )

    def forward(self, data, edge_index=None, batch=None):
        if isinstance(data, Data):
            x = data.x
            edge_index = data.edge_index
            batch = data.batch
        else:
            x = data
            if edge_index is None or batch is None:
                raise ValueError("edge_index and batch are required when Data is not provided")

        raw_x = x

        x = self.node_mlp(x)
        for conv, bn in zip(self.convs, self.bns):
            x = self.drop(self.act(bn(conv(x, edge_index))))

        x = global_mean_pool(x, batch)
        mean_q = global_mean_pool(raw_x[:, 6:7], batch)  # feat 6 = q_log

        return self.classifier(torch.cat([x, mean_q], dim=1)).squeeze(1)

def evaluator(model, loader, criterion, device):
    model.eval()
    preds, trues = [], []
    total_loss   = 0.0

    with torch.no_grad():
        for batch in loader:
            batch   = batch.to(device)
            logits  = model(batch)
            targets = batch.y.view(-1)
            loss    = criterion(logits, targets)
            total_loss += loss.item() * batch.num_graphs
            preds.extend(torch.sigmoid(logits).cpu().numpy())
            trues.extend(targets.cpu().numpy())

    avg_loss = total_loss / len(loader.dataset)
    auc = roc_auc_score(trues, preds) if len(np.unique(trues)) >= 2 else float("nan")
    return avg_loss, auc, np.array(preds), np.array(trues)

def loss_schedule(optimizer, warmup_epochs, total_epochs, steps_per_epoch):
    """
    Step-level scheduler:
      - Linear warmup for `warmup_epochs` epochs  (lr: 0 -> peak)
      - Cosine decay for remaining epochs          (lr: peak -> 0)
    Call scheduler.step() once per batch.
    """
    warmup_steps = warmup_epochs * steps_per_epoch
    total_steps  = total_epochs  * steps_per_epoch

    def lr_lambda(current_step):
        if current_step < warmup_steps:
            return float(current_step) / float(max(1, warmup_steps))
        progress = float(current_step - warmup_steps) / float(
            max(1, total_steps - warmup_steps)
        )
        return max(0.0, 0.5 * (1.0 + np.cos(np.pi * progress)))

    return torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)

def load_checkpoint(checkpoint_path, model, optimizer, scheduler, device):
    """
    Load training state from checkpoint.
    Returns: (start_epoch, best_val_auc, best_epoch, train_losses, val_losses, val_aucs, lr_history)
    """
    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint file not found: {checkpoint_path}")
    
    checkpoint = torch.load(checkpoint_path, map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])
    optimizer.load_state_dict(checkpoint["optimizer_state_dict"])
    scheduler.load_state_dict(checkpoint["scheduler_state_dict"])
    
    start_epoch = checkpoint.get("epoch", 0)
    best_val_auc = checkpoint.get("best_val_auc", -np.inf)
    best_epoch = checkpoint.get("best_epoch", -1)
    train_losses = checkpoint.get("train_losses", [])
    val_losses = checkpoint.get("val_losses", [])
    val_aucs = checkpoint.get("val_aucs", [])
    lr_history = checkpoint.get("lr_history", [])
    
    print(f"Resumed from checkpoint: epoch {start_epoch}, best AUC: {best_val_auc:.4f} @ epoch {best_epoch}")
    return start_epoch, best_val_auc, best_epoch, train_losses, val_losses, val_aucs, lr_history

def load_model_weights(weights_path, model, device):
    """Load either a raw state_dict .pt file or a training checkpoint."""
    if not os.path.exists(weights_path):
        raise FileNotFoundError(f"Weights file not found: {weights_path}")

    payload = torch.load(weights_path, map_location=device)
    if isinstance(payload, dict) and "model_state_dict" in payload:
        state_dict = payload["model_state_dict"]
    elif isinstance(payload, dict):
        state_dict = payload
    else:
        raise RuntimeError(f"Unsupported weight file format: {weights_path}")

    model.load_state_dict(state_dict)
    return payload

def build_export_graph(num_nodes, device):
    if num_nodes < 2:
        raise ValueError("--num_nodes must be at least 2 for ONNX export")

    x = torch.zeros((num_nodes, N_FEATURES), dtype=torch.float32, device=device)
    src = torch.arange(num_nodes - 1, dtype=torch.long, device=device)
    dst = src + 1
    edge_index = torch.stack([
        torch.cat([src, dst]),
        torch.cat([dst, src]),
    ], dim=0)
    batch = torch.zeros(num_nodes, dtype=torch.long, device=device)
    return x, edge_index, batch

def export_onnx(args):
    device = torch.device("cpu")
    # Try to load config from checkpoint if available
    config = None
    if args.weights.endswith(".pt"):
        checkpoint = torch.load(args.weights, map_location=device)
        if isinstance(checkpoint, dict) and "config" in checkpoint:
            config = checkpoint["config"]
    # Priority: explicit args > config > defaults
    hidden_dim = getattr(args, "hidden_dim", None)
    if hidden_dim is None and config and "hidden_dim" in config:
        hidden_dim = config["hidden_dim"]
    if hidden_dim is None:
        hidden_dim = 256

    num_layers = getattr(args, "num_layers", None)
    if num_layers is None and config and "num_layers" in config:
        num_layers = config["num_layers"]
    if num_layers is None:
        num_layers = 7

    dropout = getattr(args, "dropout", None)
    if dropout is None and config and "dropout" in config:
        dropout = config["dropout"]
    if dropout is None:
        dropout = 0.4

    model = SuperGNN(
        input_dim=N_FEATURES,
        hidden_dim=hidden_dim,
        dropout=dropout,
        num_layers=num_layers
    ).to(device)
    load_model_weights(args.weights, model, device)
    model.eval()

    x, edge_index, batch = build_export_graph(args.num_nodes, device)

    onnx_out = args.onnx_out
    if onnx_out is None:
        root, _ = os.path.splitext(args.weights)
        onnx_out = root + ".onnx"

    out_dir = os.path.dirname(onnx_out)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    torch.onnx.export(
        model,
        (x, edge_index, batch),
        onnx_out,
        export_params=True,
        opset_version=args.opset,
        do_constant_folding=True,
        input_names=["x", "edge_index", "batch"],
        output_names=["logits"],
        dynamic_axes={
            "x": {0: "num_nodes"},
            "edge_index": {1: "num_edges"},
            "batch": {0: "num_nodes"},
            "logits": {0: "num_graphs"},
        },
    )
    print(f"Saved ONNX model -> {onnx_out}")

def prepare_training_data(args):
    set_seed(42)

    if not os.path.exists(args.geo):
        print(f"ERROR: geometry file not found: {args.geo}", file=sys.stderr)
        sys.exit(1)

    holdout_frac = args.val_frac + args.test_frac
    if holdout_frac <= 0.0 or holdout_frac >= 1.0:
        raise ValueError("val_frac + test_frac must be between 0 and 1")

    geo      = pd.read_csv(args.geo)
    geo_dict = icecube_geom(geo)
    print(f"Geometry: {len(geo_dict)} DOM entries")

    dataset = TauDataloader(
        nue_dbs              = args.nue_dbs,
        tau_dbs              = args.tau_dbs,
        geo_dict             = geo_dict,
        max_events_per_class = args.max_events,
        charge_threshold     = args.charge_threshold,
    )

    indices = np.arange(len(dataset))
    labels  = np.array([dataset[i].y.item() for i in range(len(dataset))])

    train_idx, holdout_idx = train_test_split(
        indices, test_size=holdout_frac, stratify=labels, random_state=42
    )
    val_idx, test_idx = train_test_split(
        holdout_idx,
        test_size    = args.test_frac / holdout_frac,
        stratify     = labels[holdout_idx],
        random_state = 42,
    )

    train_ds = dataset[train_idx.tolist()]
    val_ds   = dataset[val_idx.tolist()]
    test_ds  = dataset[test_idx.tolist()]
    print(f"Split -> train: {len(train_ds)}  val: {len(val_ds)}  test: {len(test_ds)}")

    return {
        "train_ds": train_ds,
        "val_ds": val_ds,
        "test_ds": test_ds,
        "train_idx": train_idx,
        "val_idx": val_idx,
        "test_idx": test_idx,
        "train_labels": labels[train_idx],
    }


def create_dataloaders(data_bundle, batch_size):
    num_workers = min(4, os.cpu_count() or 1)
    pin_memory = torch.cuda.is_available()

    train_loader = DataLoader(
        data_bundle["train_ds"],
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )
    val_loader = DataLoader(
        data_bundle["val_ds"],
        batch_size=batch_size,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )
    test_loader = DataLoader(
        data_bundle["test_ds"],
        batch_size=batch_size,
        num_workers=num_workers,
        pin_memory=pin_memory,
    )
    return train_loader, val_loader, test_loader


